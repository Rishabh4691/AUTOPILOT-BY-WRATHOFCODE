const date = (sec, lang, plusDays = 0) =>
  sec ? new Date((sec + plusDays * 86400) * 1000).toLocaleDateString(lang === 'de' ? 'de-DE' : 'en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : '—'

function Field({ label, value, mono }) {
  return (
    <div className="min-w-0">
      <dt className="text-[10px] tracking-[0.14em] text-[#6b665e] uppercase">{label}</dt>
      <dd className={`mt-0.5 truncate text-[13px] text-[#0d0d0d] ${mono ? 'font-mono' : ''}`}>{value || '—'}</dd>
    </div>
  )
}

/** A printable invoice for one booking. Shows and prints; it sends nothing. */
export default function Invoice({ booking: s, onClose }) {
  const [lang] = useLang()
  const c = COPY[lang] ?? COPY.en
  const [rfq, setRfq] = useState(null)
  const [loading, setLoading] = useState(!!s.rfq_id)

  useEffect(() => {
    if (!s.rfq_id) return
    get(`/rfqs/${encodeURIComponent(s.rfq_id)}`)
      .then(setRfq)
      .catch(() => setRfq(null))
      .finally(() => setLoading(false))
  }, [s.rfq_id])

  useEffect(() => {
    document.body.classList.add('invoice-open')
    const esc = (e) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', esc)
    return () => {
      document.body.classList.remove('invoice-open')
      window.removeEventListener('keydown', esc)
    }
  }, [onClose])

  const b = rfq?.breakdown
  const currency = b?.currency || s.currency || rfq?.currency || 'EUR'
  const total = b?.total ?? (s.price != null ? Number(s.price) : rfq?.total ?? null)
  const lines = b?.lines?.length
    ? b.lines
    : total != null
      ? [{ label: `${c.freight} ${s.origin} → ${s.destination} · ${s.carrier ?? ''}`.trim(), amount: total }]
      : []
  const number = `INV-${(s.team_reference || s.booking_reference || s.rfq_id || 'DRAFT').replace(/^(WOC-|BK-)/, '')}`
  const customer = s.customer && s.customer !== '—' ? s.customer : rfq?.customer
  const company = customer?.includes('@') ? customer.split('@')[0].replace(/[-_.]+/g, ' ').replace(/\b\w/g, (m) => m.toUpperCase()) : customer

  return createPortal(
    <div className="invoice-layer fixed inset-0 z-[60] overflow-y-auto bg-black/55 px-4 py-8 backdrop-blur-sm" onClick={onClose} role="dialog" aria-modal="true" aria-label={`${c.invoice} ${number}`}>
      <div className="mx-auto max-w-3xl" onClick={(e) => e.stopPropagation()}>
        <div className="invoice-actions mb-4 flex items-center justify-end gap-3">
          <button type="button" onClick={() => window.print()} className="glass inline-flex min-h-11 cursor-pointer items-center gap-2 rounded-full px-5 text-sm font-semibold text-white">
            <Printer className="size-4" aria-hidden /> {c.print}
          </button>
          <button type="button" onClick={onClose} aria-label={c.close} className="glass inline-flex size-11 cursor-pointer items-center justify-center rounded-full text-white">
            <X className="size-5" aria-hidden />
          </button>
        </div>

        <article className="invoice-paper rounded-[28px] bg-[#fffdf8] p-8 text-[#0d0d0d] shadow-2xl sm:p-12">
          <header className="flex flex-wrap items-start justify-between gap-6 border-b-2 border-[#0d0d0d] pb-6">
            <div>
              <div className="font-display text-[28px] leading-none tracking-tight">WRATHOFCODE</div>
              <div className="mt-1 text-[12px] text-[#6b665e]">AUTOPILOT · digital air forwarder · START Hack Munich 2026</div>
            </div>
            <div className="text-right">
              <div className="font-display text-[34px] leading-none text-[#ff6b2c]">{c.invoice}</div>
              <dl className="mt-3 space-y-0.5 text-[12px]">
                <div><span className="text-[#6b665e]">{c.number} </span><span className="font-mono">{number}</span></div>
                <div><span className="text-[#6b665e]">{c.issued} </span>{date(s.booked_at, lang)}</div>
                <div><span className="text-[#6b665e]">{c.due} </span>{date(s.booked_at, lang, 14)}</div>
              </dl>
            </div>
          </header>

          {loading ? (
            <p className="py-16 text-center text-[#6b665e]">{c.loading}</p>
          ) : (
            <>
              <section className="mt-6 grid gap-6 sm:grid-cols-2">
                <div>
                  <h2 className="text-[10px] tracking-[0.14em] text-[#6b665e] uppercase">{c.billTo}</h2>
                  <p className="mt-1 text-[15px] font-semibold">{company || c.customerUnknown}</p>
                  {customer?.includes('@') && <p className="font-mono text-[12px] text-[#3a3733]">{customer}</p>}
                </div>
                <div>
                  <h2 className="text-[10px] tracking-[0.14em] text-[#6b665e] uppercase">{c.shipment}</h2>
                  <dl className="mt-1 grid grid-cols-2 gap-x-4 gap-y-2">
                    <Field label={c.booking} value={s.booking_reference} mono />
                    <Field label={c.ourRef} value={s.team_reference || s.rfq_id} mono />
                    <Field label={c.lane} value={s.origin && s.destination ? `${s.origin} → ${s.destination}` : null} mono />
                    <Field label={c.airline} value={s.carrier} />
                    <Field label={c.weight} value={s.weight_kg ? `${s.weight_kg} kg` : null} />
                    <Field label={c.chargeable} value={b?.chargeable_kg ?? rfq?.chargeable_kg ? `${b?.chargeable_kg ?? rfq?.chargeable_kg} kg` : null} />
                  </dl>
                </div>
              </section>

              <table className="mt-8 w-full text-[13px]">
                <thead>
                  <tr className="border-b border-[#0d0d0d] text-left text-[10px] tracking-[0.14em] text-[#6b665e] uppercase">
                    <th className="py-2 font-medium">{c.item}</th>
                    <th className="py-2 text-right font-medium">{c.amount}</th>
                  </tr>
                </thead>
                <tbody>
                  {lines.map((l) => (
                    <tr key={l.label} className="border-b border-[#ebe5da]">
                      <td className="py-2.5 pr-4">{l.label}</td>
                      <td className="py-2.5 text-right font-mono">{money(l.amount, currency)}</td>
                    </tr>
                  ))}
                </tbody>
                <tfoot>
                  <tr>
                    <td className="pt-4 text-right text-[12px] tracking-[0.12em] text-[#6b665e] uppercase">{c.total}</td>
                    <td className="font-display pt-4 text-right text-[22px]">{total != null ? money(total, currency) : '—'}</td>
                  </tr>
                </tfoot>
              </table>
              {total == null && <p className="mt-3 rounded-xl bg-[#fff1e8] px-4 py-3 text-[12px] text-[#a3380f]">{c.noPrice}</p>}

              <p className="mt-8 text-[12px] text-[#3a3733]">{c.terms}</p>

              {rfq?.email_body && (
                <section className="mt-8 border-t border-[#ebe5da] pt-6">
                  <h2 className="text-[10px] tracking-[0.14em] text-[#6b665e] uppercase">{c.emailTitle}</h2>
                  <pre className="mt-2 whitespace-pre-wrap rounded-xl bg-[#f7f2e8] p-4 font-sans text-[12.5px] leading-relaxed text-[#1c1b19]">{rfq.email_body}</pre>
                </section>
              )}
            </>
          )}

          <footer className="mt-10 border-t border-[#ebe5da] pt-4 text-center text-[11px] text-[#6b665e]">{c.footer}</footer>
        </article>
      </div>
    </div>,
    document.body,
  )
}
